"""Cross-engine URDF conformance: load Pinocchio_Models URDFs in MuJoCo and Drake.

Verifies that the URDF generated by Pinocchio_Models loads cleanly in real
MuJoCo and real Drake (pydrake), and that the resulting model fingerprint
(total mass, segment masses, joint count) agrees with the canonical
standard / Pinocchio model within documented tolerances (issue #437).

Skips cleanly when either engine is not installed.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import pytest

from pinocchio_models.model_pack import list_exercises
from pinocchio_models.shared.parity._canonical import conformance
from pinocchio_models.shared.parity.cross_engine import (
    EXPECTED_SEGMENTS,
    drake_fingerprint,
    load_urdf_in_drake,
    load_urdf_in_mujoco,
    mujoco_fingerprint,
    urdf_expected_fingerprint,
)
from pinocchio_models.shared.parity.fingerprint import build_urdf

REPO_ROOT = Path(__file__).resolve().parents[2]
PARITY_DIR = REPO_ROOT / "src" / "pinocchio_models" / "shared" / "parity"
URDF_LEDGER = PARITY_DIR / "cross_engine_divergences.json"

STD = conformance.load_standard()
EXERCISES = list_exercises()


def _load_ledger() -> dict[str, Any]:
    """Load documented cross-engine URDF divergences."""
    if not URDF_LEDGER.is_file():
        return {}
    return json.loads(URDF_LEDGER.read_text(encoding="utf-8")).get("divergences", {})


# =============================================================================
# MuJoCo Cross-Engine Tests
# =============================================================================


@pytest.mark.parametrize("exercise", EXERCISES)
def test_urdf_loads_in_real_mujoco(exercise: str) -> None:
    """URDF must load into real MuJoCo without parsing errors."""
    pytest.importorskip("mujoco")
    urdf = build_urdf(exercise)
    model = load_urdf_in_mujoco(urdf)
    assert model.nbody >= 1 + 15
    assert model.njnt >= 28


@pytest.mark.parametrize("exercise", EXERCISES)
def test_urdf_joint_count_in_mujoco(exercise: str) -> None:
    """Loaded URDF in MuJoCo must have exactly 28 human hinge joints."""
    pytest.importorskip("mujoco")
    urdf = build_urdf(exercise)
    model = load_urdf_in_mujoco(urdf)
    fp = mujoco_fingerprint(model)
    assert fp["joint_count"] == 28


@pytest.mark.parametrize("exercise", EXERCISES)
def test_urdf_total_mass_in_mujoco(exercise: str) -> None:
    """Total mass in MuJoCo must match expected URDF total mass."""
    pytest.importorskip("mujoco")
    urdf = build_urdf(exercise)
    model = load_urdf_in_mujoco(urdf)
    fp = mujoco_fingerprint(model)
    expected = urdf_expected_fingerprint(urdf)
    tol = float(STD["tolerances"]["mass_rel"])

    ledger = _load_ledger()
    divergence_key = f"total_mass.{exercise}.mujoco"
    if divergence_key in ledger:
        return

    assert fp["total_mass_kg"] == pytest.approx(expected["total_mass_kg"], rel=tol)


@pytest.mark.parametrize("exercise", EXERCISES)
def test_urdf_segment_masses_in_mujoco(exercise: str) -> None:
    """Canonical human segment masses in MuJoCo match expected URDF link masses."""
    pytest.importorskip("mujoco")
    urdf = build_urdf(exercise)
    model = load_urdf_in_mujoco(urdf)
    fp = mujoco_fingerprint(model)
    expected = urdf_expected_fingerprint(urdf)
    ledger = _load_ledger()
    tol = float(STD["tolerances"]["mass_rel"])

    for seg in EXPECTED_SEGMENTS:
        divergence_key = f"segment_mass.{exercise}.{seg}"
        if divergence_key in ledger:
            continue

        exp_mass = expected["segment_masses_kg"].get(seg, 0.0)
        actual_mass = fp["segment_masses_kg"].get(seg, 0.0)
        assert actual_mass == pytest.approx(exp_mass, rel=tol), (
            f"Segment {seg} mass mismatch in {exercise}: "
            f"expected={exp_mass} mujoco={actual_mass}"
        )


def test_cross_engine_ledger_no_stale_entries() -> None:
    """Every divergence in the URDF ledger corresponds to an actual difference."""
    pytest.importorskip("mujoco")
    ledger = _load_ledger()
    if not ledger:
        return

    stale: list[str] = []
    tol = float(STD["tolerances"]["mass_rel"])
    for key in ledger:
        parts = key.split(".")
        if len(parts) != 3:
            continue
        kind, exercise, target = parts
        urdf = build_urdf(exercise)
        model = load_urdf_in_mujoco(urdf)
        fp = mujoco_fingerprint(model)
        expected = urdf_expected_fingerprint(urdf)

        if kind == "segment_mass":
            exp_mass = expected["segment_masses_kg"].get(target, 0.0)
            actual_mass = fp["segment_masses_kg"].get(target, 0.0)
            if abs(actual_mass - exp_mass) <= tol * max(exp_mass, 1e-6):
                stale.append(key)
        elif kind == "total_mass":
            exp_total = expected["total_mass_kg"]
            actual_total = fp["total_mass_kg"]
            if abs(actual_total - exp_total) <= tol * exp_total:
                stale.append(key)

    assert not stale, f"Stale ledger entries found: {stale}"


