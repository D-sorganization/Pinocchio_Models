"""Pinocchio engine fingerprint (schema ``model-fingerprint/v1``).

Builds an exercise URDF, loads it in the REAL Pinocchio engine with a
free-flyer root and reports what the engine sees, for comparison against the
canonical parity standard (see ``_canonical/conformance.py``).

Engine notes:

* Gravity is not part of URDF. Pinocchio's default ``model.gravity`` is
  ``(0, 0, -9.81)``; :func:`load_model` sets it from the standard
  (9.80665 m/s^2) explicitly, as the repo convention requires.
* Pinocchio has no contact model, so ``ground_friction`` is omitted.
* Barbell and fixture bodies are fixed-joint children that Pinocchio merges
  into their parent joint's inertia; human segment masses are therefore read
  from a second engine model built from the URDF with every fixed-joint
  subtree removed (except the bench_press pelvis weld, which supports the
  supine lifter and must stay).
"""

from __future__ import annotations

import logging
import xml.etree.ElementTree as ET
from typing import Any

from pinocchio_models.model_pack import list_exercises, manifest
from pinocchio_models.shared.parity import axes_probe
from pinocchio_models.shared.parity._canonical import assemble, conformance, spec

logger = logging.getLogger(__name__)

ENGINE = "pinocchio"

# Pinocchio joint name -> canonical coordinate name (only names that differ).
COORDINATE_ALIASES: dict[str, str] = {}

# Pinocchio body (link) name -> canonical segment name; names already match.
SEGMENT_ALIASES: dict[str, str] = {}


def _link_of(joint: ET.Element, tag: str) -> str:
    """Return the ``link`` attribute of a joint's ``<parent>``/``<child>``."""
    node = joint.find(tag)
    return "" if node is None else node.get("link", "")


def _is_fixture(joint: ET.Element) -> bool:
    """A fixed joint that attaches a barbell or fixture (not the supine pelvis)."""
    return joint.get("type") == "fixed" and _link_of(joint, "child") != "pelvis"


def _fixed_subtree_links(joints: list[ET.Element]) -> set[str]:
    """Return every link at or below a fixture joint's child."""
    doomed: set[str] = set()
    frontier = [_link_of(j, "child") for j in joints if _is_fixture(j)]
    while frontier:
        link = frontier.pop()
        doomed.add(link)
        frontier += [
            _link_of(j, "child") for j in joints if _link_of(j, "parent") == link
        ]
    return doomed


def _strip_fixed_subtrees(urdf: str) -> str:
    """Return *urdf* without fixed joints and the links hanging below them."""
    root = ET.fromstring(urdf)  # nosec B314 -- urdf is self-generated by build_urdf
    joints = root.findall("joint")
    doomed = _fixed_subtree_links(joints)
    for j in joints:
        if _is_fixture(j) or _link_of(j, "child") in doomed:
            root.remove(j)
    for link_el in root.findall("link"):
        if link_el.get("name") in doomed:
            root.remove(link_el)
    return ET.tostring(root, encoding="unicode")


def build_urdf(exercise: str) -> str:
    """Return the URDF string for a manifest exercise id."""
    from pinocchio_models.__main__ import _BUILDERS, _MANIFEST_ID_ALIASES

    if exercise not in list_exercises():
        raise ValueError(f"unknown exercise {exercise!r}")
    return _BUILDERS[_MANIFEST_ID_ALIASES.get(exercise, exercise)]()


def load_model(
    urdf: str,
    std: dict[str, Any] | None = None,
    root_joint: str | None = None,
) -> Any:
    """Load *urdf* in Pinocchio with standard gravity and specified root joint."""
    import numpy as np
    import pinocchio as pin

    std = std or conformance.load_standard()
    if root_joint is None:
        root_joint = "weld" if '<link name="bench"' in urdf else "free"

    if root_joint == "weld":
        model = pin.buildModelFromXML(urdf)
    else:
        model = pin.buildModelFromXML(urdf, pin.JointModelFreeFlyer())
    model.gravity.linear = np.array([0.0, 0.0, -std["frame"]["gravity_mps2"]])
    return model


def _measure(
    urdf: str,
    std: dict[str, Any],
    root_joint: str = "free",
) -> tuple[dict[str, float], dict[str, list[float]]]:
    """Raw per-body masses and neutral world origins (engine frame).

    Read from a model with fixed-joint subtrees removed, because Pinocchio
    merges those bodies into their parent joint's inertia.
    """
    import pinocchio as pin

    model = load_model(_strip_fixed_subtrees(urdf), std, root_joint=root_joint)
    data = model.createData()
    pin.forwardKinematics(model, data, pin.neutral(model))
    pin.updateFramePlacements(model, data)
    masses: dict[str, float] = {}
    origins: dict[str, list[float]] = {}
    for fid, frame in enumerate(model.frames):
        if frame.type == pin.FrameType.BODY:
            masses[frame.name] = float(model.inertias[frame.parentJoint].mass)
            origins[frame.name] = [float(v) for v in data.oMf[fid].translation]
    return masses, origins


def _limits(model: Any) -> dict[str, tuple[float, float]]:
    """Raw 1-DOF joint limits keyed by engine joint name."""
    out: dict[str, tuple[float, float]] = {}
    for jid in range(1, model.njoints):  # 0 = universe
        joint = model.joints[jid]
        if joint.nq == 1:
            q = joint.idx_q
            out[model.names[jid]] = (
                float(model.lowerPositionLimit[q]),
                float(model.upperPositionLimit[q]),
            )
    return out


def objective_phase_names(
    exercise: str, std: dict[str, Any] | None = None
) -> list[str]:
    """Ordered phase names of the pack objective for a standard *exercise*.

    The objective is looked up by the standard's own ``legacy_key`` (``squat``
    is the ``back_squat`` objective), so the pack keeps no id table of its own.
    The names are measured from the objective, not copied from the standard,
    so ``spec.check_fingerprint`` can catch an objective that drifts from the
    standard's ordered phases (Repository_Management#2025).

    Raises ValueError for an exercise the standard does not define, or for an
    objective without phases.
    """
    from pinocchio_models.optimization.objectives.registry import (
        get_exercise_objective,
    )

    std = conformance.load_standard() if std is None else std
    block = spec.exercise_spec(std, exercise)  # precondition: known exercise
    objective = get_exercise_objective(str(block.get("legacy_key", exercise)))
    names = [phase.name for phase in objective.phases]
    if not names:  # postcondition: assemble_fingerprint needs a non-empty list
        raise ValueError(f"{exercise!r} objective defines no phases")
    return names


def fingerprint(exercise: str) -> dict[str, Any]:
    """Build *exercise*, load it in Pinocchio and return its fingerprint."""
    std = conformance.load_standard()
    version = ""
    rj = spec.root_joint(std, exercise)
    try:
        import pinocchio as pin

        version = str(pin.__version__)
        urdf = build_urdf(exercise)
        model = load_model(urdf, std, root_joint=rj)
        masses, origins = _measure(urdf, std, root_joint=rj)
    except Exception as exc:  # noqa: BLE001 - any load failure is reported
        logger.warning("%s failed to load in %s: %s", exercise, ENGINE, exc)
        return assemble.failed_fingerprint(ENGINE, version, exercise, exc)
    names = objective_phase_names(exercise, std)
    return assemble.assemble_fingerprint(
        engine=ENGINE,
        engine_version=version,
        exercise=exercise,
        std=std,
        root_joint="free"
        if (model.njoints > 1 and model.joints[1].nq == 7)
        else "weld",
        gravity_engine=[float(v) for v in model.gravity.linear],
        segment_masses_kg=masses,
        coordinate_limits_rad=_limits(model),
        segment_origins_engine_m=origins,
        capabilities=assemble.capabilities_from_manifest(manifest(), std),
        coordinate_aliases=COORDINATE_ALIASES,
        segment_aliases=SEGMENT_ALIASES,
        phase_count=len(names),
        # Standard v2.0 conformance criterion 3: the ordered phase names, a core
        # assemble_fingerprint field since Repository_Management#2089.
        phase_names=names,
        coordinate_axes_engine=axes_probe.coordinate_axes(
            model, std, COORDINATE_ALIASES
        ),
        pelvis_rotation_engine=axes_probe.pelvis_rotation(model),
        segment_origins_test_poses_engine_m=axes_probe.pose_origins(
            model, std, COORDINATE_ALIASES
        ),
    )


def main(argv: list[str] | None = None) -> int:
    """CLI: write fingerprint JSON for one exercise or all of them."""
    return assemble.run_fingerprint_cli(argv, fingerprint, list_exercises(), ENGINE)


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
